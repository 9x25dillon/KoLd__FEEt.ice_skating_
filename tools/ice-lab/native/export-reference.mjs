import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve, join, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { strict as assert } from 'node:assert';

export const PIN = '8d89af29caa14ee413e94fc821c76458d8974836';
const base = 'tools/ice-lab/';
const here = dirname(fileURLToPath(import.meta.url));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const hex = value => {
  // NaN payloads are outside the replay contract; normalize math-corpus NaNs.
  if (Number.isNaN(value)) return '7ff8000000000000';
  const b = Buffer.alloc(8); b.writeDoubleBE(value); return b.toString('hex');
};
const pointer = (p, key) => p + '/' + String(key).replaceAll('~', '~0').replaceAll('/', '~1');

export function canonical(value) {
  return JSON.stringify(value, (key, v) => {
    if (typeof v === 'number' && !Number.isFinite(v)) {
      if (v === Infinity && key === 'turnRadius') return '+Infinity';
      throw new Error('Non-finite canonical value at key ' + key);
    }
    return v && typeof v === 'object' && !Array.isArray(v)
      ? Object.fromEntries(Object.keys(v).sort().map(k => [k, v[k]])) : v;
  });
}

function numericBits(value, path = '', out = {}) {
  if (typeof value === 'number') out[path] = hex(value);
  else if (value && typeof value === 'object') {
    const keys = Array.isArray(value) ? Object.keys(value) : Object.keys(value).sort();
    for (const k of keys) numericBits(value[k], pointer(path, k), out);
  }
  return out;
}

// This intentionally recognizes only the pinned interfaces' small grammar.
// An unrecognized member/type fails instead of silently omitting a wire field.
function interfaces(source) {
  const clean = source.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  return [...clean.matchAll(/export interface (\w+)\s*\{([^}]+)\}/g)].map(([, name, body]) => ({
    name, fields: body.split(';').map(s => s.trim()).filter(Boolean).map(s => {
      const m = /^(\w+):\s*([\w\s,\[\]]+)$/.exec(s);
      assert(m, 'Unrecognized interface member: ' + s);
      return { name: m[1], type: m[2].trim() };
    }),
  }));
}

function cppHeader(types) {
  const known = new Set(types.map(t => t.name));
  const numeric = new Set(['number', 'Foot', 'Depth', 'Regime', 'Fall', 'EventType']);
  function cpp(type) {
    if (numeric.has(type)) return 'double'; // JS numbers, including enum codes and negative tick sentinels
    if (type === 'boolean') return 'bool';
    if (known.has(type)) return type;
    const tuple = /^\[(\w+),\s*\1\]$/.exec(type);
    assert(tuple && known.has(tuple[1]), 'Unsupported wire type: ' + type);
    return `std::array<${tuple[1]}, 2>`;
  }
  let out = `// Generated by export-reference.mjs from ${PIN}; do not edit.\n#pragma once\n#include <array>\n#include <cstddef>\n#include <limits>\n#include <type_traits>\nnamespace KoLd { namespace Wire {\nstatic_assert(sizeof(double) == 8 && std::numeric_limits<double>::is_iec559, "binary64 required");\n`;
  for (const t of types) {
    out += `struct ${t.name} {\n` + t.fields.map(f => `  ${cpp(f.type)} ${f.name}{};\n`).join('') + '};\n';
    out += `static_assert(std::is_standard_layout<${t.name}>::value, "value type required");\n`;
    for (const qualifier of ['', 'const ']) {
      out += `template<class F> void Fields(${qualifier}${t.name}& v, F&& f) {\n`;
      for (const f of [...t.fields].sort((a, b) => a.name < b.name ? -1 : 1)) out += `  f("${f.name}", v.${f.name});\n`;
      out += '}\n';
    }
  }
  out += `constexpr std::size_t ParamCount = ${types.find(t => t.name === 'Params').fields.length};\nconstexpr std::size_t InputCount = ${types.find(t => t.name === 'SkatingInput').fields.length};\nstatic_assert(ParamCount == 93 && InputCount == 13, "pinned wire counts");\n}}\n`;
  return out;
}

export async function artifacts() {
  const git = (...args) => execFileSync('git', ['-C', here, ...args], { maxBuffer: 64 * 1024 * 1024 });
  const root = git('rev-parse', '--show-toplevel').toString().trim();
  const paths = execFileSync('git', ['-C', root, 'ls-tree', '-r', '--name-only', PIN, base + 'sim']).toString().trim().split('\n');
  const scratch = mkdtempSync(join(tmpdir(), 'kold-reference-'));
  const sourceHashes = {};
  try {
    writeFileSync(join(scratch, 'package.json'), '{"type":"module"}\n');
    for (const path of paths) {
      assert(path.startsWith(base + 'sim/') && path.endsWith('.ts'));
      const bytes = git('show', PIN + ':' + path);
      sourceHashes[path] = sha(bytes);
      const dest = join(scratch, path.slice(base.length));
      mkdirSync(dirname(dest), { recursive: true }); writeFileSync(dest, bytes);
    }
    const replayBytes = git('show', PIN + ':' + base + 'test/fixtures/replay-v1.json');
    const load = name => import(pathToFileURL(join(scratch, 'sim', name + '.ts')).href);
    const [replay, solver, params, vocabulary, math] = await Promise.all(['replay', 'solver', 'params', 'types', 'math'].map(load));
    assert.equal(replay.REPLAY_SOLVER, 'ice-lab-f64/5');
    const clip = replay.parseReplay(replayBytes.toString('utf8'));
    assert.equal(clip.frames.length, 240);
    assert.equal(clip.frames[0].digest, 653800387);
    assert.equal(clip.frames.at(-1).digest, 2115996402);
    for (const p of [clip.initial.params, ...clip.frames.filter(f => f.params).map(f => f.params)])
      assert(p.jumpMode === 0 && p.movesMode === 0, 'ground-v1 only');
    const state = solver.createState(clip.initial.params, clip.initial.speed, clip.initial.lean);
    const rows = [];
    const row = (tick, events) => {
      const text = canonical([state, events]);
      const crc = math.crc32(new TextEncoder().encode(text));
      assert.equal(crc, replay.replayDigest(state, events));
      if (tick) assert.equal(crc, clip.frames[tick - 1].digest, 'reference divergence at tick ' + tick);
      rows.push({ tick, canonical: text, crc, bits: numericBits([state, events]) });
    };
    row(0, []);
    let active = clip.initial.params;
    for (const [i, f] of clip.frames.entries()) {
      if (f.params) active = f.params;
      const events = []; solver.step(state, f.input, active, params.SIM_DT, events); row(i + 1, events);
    }
    const header = { schema: 'kold-parity-oracle/1', sourceCommit: PIN, sourceSolver: replay.REPLAY_SOLVER,
      replaySchema: replay.REPLAY_SCHEMA, capability: 'ground-v1', replaySha256: sha(replayBytes), hz: params.SIM_HZ, frameCount: clip.frames.length };
    const types = ['math', 'params', 'types'].flatMap(name => interfaces(readFileSync(join(scratch, 'sim', name + '.ts'), 'utf8')));
    assert.deepEqual(types.find(t => t.name === 'Params').fields.map(f => f.name), Object.keys(params.DEFAULT_PARAMS));
    assert.deepEqual(types.find(t => t.name === 'SkatingInput').fields.map(f => f.name), Object.keys(vocabulary.NEUTRAL_INPUT));
    const manifest = { schema: 'kold-wire-manifest/1', sourceCommit: PIN, types,
      replayKeys: ['schema', 'solver', 'hz', 'initial', 'frames'], initialSpeed: [-100, 100], initialLean: [-1.55, 1.55],
      parameterBounds: Object.fromEntries(Object.keys(params.DEFAULT_PARAMS).map(k => [k,
        ['mass', 'gravity', 'comHeight', 'rocker', 'rockerToeFraction', 'minSpeedForCurv'].includes(k) ? [1e-6, 1e6] :
        ['maxLean', 'maxTilt', 'fallLean'].includes(k) ? [0, 1.55] : [0, 1e6]])),
      inputBounds: { lean: [-1, 1], pitch: [-1, 1], leanSplit: [-1, 1], knee: [0, 1], weight: [0, 1], carriage: [0, 1] } };
    // Adversarial rounding corpus: random binary64 bits plus decimal-format boundaries.
    const numbers = [0, -0, 0.1, 1/3, 1e-6, 1e-7, 1e20, 1e21, Number.MIN_VALUE, Number.MAX_VALUE,
      9007199254740992, 1000000000000000100, 0.49999999999999994, -0.49999999999999994];
    let seed = 0x12345678;
    const randomWord = () => { seed ^= seed << 13; seed ^= seed >>> 17; seed ^= seed << 5; return seed >>> 0; };
    for (let i = 0; i < 8192; ++i) {
      const b = Buffer.alloc(8); b.writeUInt32BE(randomWord(), 0); b.writeUInt32BE(randomWord(), 4);
      const n = b.readDoubleBE(); if (Number.isFinite(n)) numbers.push(n);
    }
    const files = new Map([
      ['replay-v1.json', replayBytes],
      ['oracle.jsonl', [header, ...rows].map(v => JSON.stringify(v)).join('\n') + '\n'],
      ['wire-manifest.json', JSON.stringify(manifest, null, 2) + '\n'],
      ['KoLdWireTypes.h', cppHeader(types)],
      ['numbers.tsv', numbers.map(n => hex(n) + '\t' + JSON.stringify(n)).join('\n') + '\n'],
    ]);
    const mathRows = [];
    const samples = [0, -0, Infinity, -Infinity, NaN, Number.MIN_VALUE, -Number.MIN_VALUE,
      Number.MAX_VALUE, -Number.MAX_VALUE, 0.49999999999999994, -0.49999999999999994];
    for (const boundary of [7.450580596923828e-9, 0.4375, 0.5, 0.6875, Math.PI/4, 0.975, 1, 1.1875, 2.4375, 7.378697629483821e19])
      for (const delta of [-Number.EPSILON, 0, Number.EPSILON]) samples.push(boundary + delta, -boundary + delta);
    for (let i = 0; i < 1024; ++i) samples.push((randomWord() / 4294967296 - 0.5) * 2000, (randomWord() / 4294967296 - 0.5) * 2);
    const functions = { ...math, round: Math.round };
    for (const name of ['sin', 'cos', 'tan', 'atan', 'asin', 'round'])
      for (const x of samples) mathRows.push([name, hex(x), hex(0), hex(functions[name](x))].join(' '));
    for (const y of [0, -0, 1, -1, Infinity, -Infinity, Number.MIN_VALUE, -Number.MIN_VALUE, NaN])
      for (const x of samples.slice(0, 80)) mathRows.push(['atan2', hex(y), hex(x), hex(math.atan2(y, x))].join(' '));
    for (let i = 1; i < samples.length; ++i) mathRows.push(['atan2', hex(samples[i - 1]), hex(samples[i]), hex(math.atan2(samples[i - 1], samples[i]))].join(' '));
    files.set('math.tsv', mathRows.join('\n') + '\n');
    const mutations = [];
    for (const [name, mutate] of [
      ['recorded-digest-frame-4', c => { c.frames[4].digest = (c.frames[4].digest ^ 1) >>> 0; }],
      ['brake-frame-100', c => { c.frames[100].input.brake = !c.frames[100].input.brake; }],
    ]) {
      const changed = structuredClone(clip); mutate(changed);
      const player = new replay.ReplayPlayer(changed);
      while (!player.done) player.advance();
      assert(player.divergence, name + ' must diverge');
      const tick = player.divergence.tick;
      const actual = numericBits([player.state, player.events]);
      const firstPath = Object.keys(rows[tick].bits).find(path => rows[tick].bits[path] !== actual[path]);
      mutations.push({ name, ...player.divergence, ticksAttempted: player.index,
        firstNumericDifference: firstPath ? { path: firstPath, expectedBits: rows[tick].bits[firstPath], actualBits: actual[firstPath] } : null });
    }
    files.set('measured-mutations.json', JSON.stringify({ sourceCommit: PIN, evidence: 'TypeScript reference only', mutations }, null, 2) + '\n');
    // Sorted leaf tokens let C++ load every reference value through the generated fields.
    // This loads states; it does NOT execute a native solver.
    const fixtures = rows.map(r => {
      const values = [];
      const walk = (v, path) => {
        if (typeof v === 'number' || v === '+Infinity') values.push(r.bits[path]);
        else if (typeof v === 'boolean') values.push(v ? 'true' : 'false');
        else for (const key of Object.keys(v)) walk(v[key], pointer(path, key));
      };
      const pair = JSON.parse(r.canonical);
      walk(pair, '');
      return [r.tick, r.crc, pair[1].length, ...values].join(' ') + '\t' + r.canonical;
    }).join('\n') + '\n';
    files.set('states.tsv', fixtures);
    files.set('manifest.json', JSON.stringify({ ...header,
      schema: 'kold-reference-manifest/1', sourceHashes,
      files: Object.fromEntries([...files].map(([p, data]) => [p, sha(data)])),
      nativeSolverVerified: false }, null, 2) + '\n');
    return files;
  } finally { rmSync(scratch, { recursive: true, force: true }); }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    assert(process.argv.length >= 3 && process.argv.length <= 4 && (!process.argv[3] || process.argv[3] === '--check'),
      'Usage: node native/export-reference.mjs <output-directory> [--check]');
    const out = resolve(process.argv[2]);
    const files = await artifacts();
    if (process.argv[3] !== '--check') mkdirSync(out, { recursive: true });
    for (const [name, data] of files) {
      if (process.argv[3] === '--check') assert.deepEqual(readFileSync(join(out, name)), Buffer.from(data), 'stale artifact: ' + name);
      else writeFileSync(join(out, name), data);
    }
    console.log(`${process.argv[3] ? 'Checked' : 'Wrote'} ${files.size} artifacts from ${PIN}; native solver unverified.`);
  } catch (e) { console.error(e.message); process.exitCode = 1; }
}
