// tools/ice-lab/status.mjs — the README's status block, generated, never hand-kept.
//
//   node tools/ice-lab/status.mjs              print the block
//   node tools/ice-lab/status.mjs --write      rewrite it in README.md, between the status markers
//   node tools/ice-lab/status.mjs --check      exit 1 if README.md's block is not what this run produces
//   node tools/ice-lab/status.mjs --logs <dir> read the suites' TAP output from <dir> instead of
//                                              running them: ice-lab.tap, godot.tap, unreal.tap
//
// The same mechanism that keeps docs/fidelity-report.md honest (fidelity-gate
// §6.3 item 4): CI regenerates the block on every push and fails if the
// committed README differs by a byte. So the block holds only what a clean
// checkout reproduces: counts and verdicts. No date, no commit, no duration,
// no machine.
//
// Without --logs it runs the three suites itself, the way CI does, with
// UE_ROOT pointed nowhere so the two live Unreal checks skip on every machine
// and the block is the same on a laptop with Unreal as on a runner without.
// It needs `node games/ice-run-godot/tools/prepare.mjs --engine-only` first.
//
// Zero dependencies. It reads results; it changes no test and no case.

import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { validateCorpus } from "./validate.mjs";
import { SKINS } from "./game/appearance.ts";
import { VENUES } from "./game/venues.ts";
import { SKATE_PRESETS } from "./game/skates.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const README = join(ROOT, "README.md");
const BEGIN = "<!-- status:begin (generated by tools/ice-lab/status.mjs — do not edit; CI fails if it differs) -->";
const END = "<!-- status:end -->";

const SUITES = [
  { key: "ice-lab", name: "Ice Lab suite", cwd: HERE, dir: join(HERE, "test"), match: /\.test\.ts$/, show: "cd tools/ice-lab && node --test test/*.test.ts" },
  { key: "godot", name: "Godot bridge tests", cwd: ROOT, dir: join(ROOT, "games", "ice-run-godot", "tests"), match: /\.test\.mjs$/, show: "node --test games/ice-run-godot/tests/*.test.mjs" },
  { key: "unreal", name: "Unreal contract tests", cwd: ROOT, dir: join(ROOT, "games", "ice-run-unreal", "tests"), match: /\.test\.mjs$/, show: "node --test games/ice-run-unreal/tests/*.test.mjs" },
];

/** Counts from node:test's TAP summary, and the names of todo tests that are failing. */
export function parseTap(text) {
  const n = (key) => {
    const m = text.match(new RegExp(`^# ${key} (\\d+)$`, "m"));
    if (!m) throw new Error(`no "# ${key}" line in the TAP output`);
    return Number(m[1]);
  };
  const failingTodo = [...text.matchAll(/^\s*not ok \d+ - (.*?) # TODO\b/gm)].map((m) => m[1]).sort();
  return { tests: n("tests"), pass: n("pass"), fail: n("fail") + n("cancelled"), skipped: n("skipped"), todo: n("todo"), failingTodo };
}

function runSuite(suite) {
  const files = readdirSync(suite.dir).filter((f) => suite.match.test(f)).sort().map((f) => join(suite.dir, f));
  const r = spawnSync(process.execPath, ["--test", "--test-reporter=tap", ...files], {
    cwd: suite.cwd, encoding: "utf8", maxBuffer: 1 << 28,
    env: { ...process.env, UE_ROOT: join(ROOT, ".no-unreal-for-the-status-block") },
  });
  return r.stdout;
}

function replayVerdict() {
  const r = spawnSync(process.execPath, ["replay/verify.ts", "test/fixtures/replay-v1.json"], { cwd: HERE, encoding: "utf8" });
  try {
    const out = JSON.parse(r.stdout.trim().split("\n").pop());
    return out.verified === true ? `verified, ${out.ticks} ticks` : `**NOT VERIFIED** — first divergence at tick ${out.divergence?.tick ?? "?"}`;
  } catch { return "**NOT VERIFIED** — the verifier printed no result"; }
}

const CLASS = {
  carve: "O1 carve relation", tracing: "O2 tracing curvature", transition: "O3 edge transitions",
  glide: "O4 speed decay", jump: "O5 jump rotation", inertia: "O6 moment of inertia", propulsion: "O7 propulsion",
};

export function block(suites, replay, report) {
  const out = [BEGIN, ""];
  out.push("| Check | Command | Result |", "| --- | --- | --- |");
  for (const s of suites) {
    const c = s.counts;
    const parts = [`${c.pass} pass`, c.fail ? `**${c.fail} FAIL**` : "0 fail"];
    if (c.skipped) parts.push(`${c.skipped} skipped`);
    if (c.todo) parts.push(`${c.todo} todo`);
    out.push(`| ${s.name} | \`${s.show}\` | ${c.tests} tests: ${parts.join(", ")} |`);
  }
  out.push(`| Replay fixture | \`cd tools/ice-lab && node replay/verify.ts test/fixtures/replay-v1.json\` | ${replay} |`);
  const g = report.summary;
  const external = report.results.filter((r) => r.source !== "derived" && (r.verdict === "pass" || r.verdict === "fail"));
  const externalPass = external.filter((r) => r.verdict === "pass").length;
  out.push(`| Fidelity validator | \`cd tools/ice-lab && node validate.mjs\` | ${g.cases} cases: ${g.pass} pass, ${g.fail ? `**${g.fail} FAIL**` : "0 fail"}, ${g.unsourced} unsourced, ${g.unmodelled} unmodelled |`);
  out.push(`| Fidelity gate ([§6.3](docs/fidelity-gate.md#63--the-gate-is-met)) | | **${report.gate.met ? "met" : "not met"}** |`);
  out.push("");
  out.push("Fidelity coverage, external passing cases per class (three are needed in each):", "");
  out.push("| " + Object.values(CLASS).join(" | ") + " |", "|" + Object.keys(CLASS).map(() => " ---: ").join("|") + "|");
  out.push("| " + Object.keys(CLASS).map((k) => `${report.coverage[k]} / 3`).join(" | ") + " |", "");
  out.push(`External evidence: ${external.length} sourced case${external.length === 1 ? "" : "s"} measured outside the project, ${externalPass} passing, ${external.length - externalPass} failing.`);
  const content = SKINS.length + VENUES.length + SKATE_PRESETS.length;
  out.push(`Content against corpus: ${SKINS.length} costumes, ${VENUES.length} venues and ${SKATE_PRESETS.length} skate presets (${content}) `
    + `to ${externalPass} passing external case${externalPass === 1 ? "" : "s"}.`, "");
  const todo = suites.flatMap((s) => s.counts.failingTodo.map((name) => `- ${s.name}: ${name}`));
  out.push(todo.length
    ? "Tests recorded as failing and left failing (`todo`: they print on every run and do not close the build):"
    : "No test is recorded as failing.");
  out.push(...todo, "");
  out.push("As CI runs it: no Unreal Engine on the runner, so the two live Unreal checks skip. The Godot smoke test,");
  out.push("the Unreal build, the typecheck and anything on a physical pad are not in this block; see [`Hand_off.md`](Hand_off.md).", "");
  out.push(END);
  return out.join("\n");
}

function main(argv) {
  const at = argv.indexOf("--logs");
  const logs = at >= 0 && argv[at + 1] ? resolve(argv[at + 1]) : null;
  const suites = SUITES.map((s) => ({
    ...s, counts: parseTap(logs ? readFileSync(join(logs, `${s.key}.tap`), "utf8") : runSuite(s)),
  }));
  const text = block(suites, replayVerdict(), validateCorpus());
  const readme = readFileSync(README, "utf8");
  const from = readme.indexOf(BEGIN), to = readme.indexOf(END);
  if (argv.includes("--write") || argv.includes("--check")) {
    if (from < 0 || to < from) { process.stderr.write("README.md has no status markers\n"); return 1; }
    const next = readme.slice(0, from) + text + readme.slice(to + END.length);
    if (argv.includes("--check")) {
      if (next !== readme) { process.stderr.write("README.md's status block is stale: run `node tools/ice-lab/status.mjs --write`\n"); return 1; }
      process.stdout.write("README.md's status block is current\n");
      return 0;
    }
    if (next !== readme) writeFileSync(README, next);
    process.stdout.write(next !== readme ? "README.md's status block rewritten\n" : "README.md's status block unchanged\n");
    return 0;
  }
  process.stdout.write(text + "\n");
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
